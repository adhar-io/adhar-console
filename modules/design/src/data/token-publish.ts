/**
 * Design tokens ↔ code (pure, tested).
 *
 *   • Project overrides: a project's token set is the workspace set plus the
 *     tokens the project changed or added (stored as a partial set). Editing
 *     a project's tokens stores only the difference, so a later change to a
 *     workspace token the project did not touch still flows through.
 *   • Publish files: the token set as the files a repository consumes — W3C
 *     Design Tokens JSON, CSS custom properties, and Tailwind (v4 `@theme`
 *     and a v3 preset) — written into one folder in one pull request.
 */

import { CATEGORIES, mergeTokenSets, tokensToCss, tokensToTailwindV3, tokensToTailwindV4, tokensToW3C, type TokenCategory } from './tokens-lib.ts'
import type { TokenOverrides, TokenSet } from './types.ts'

/** The effective token set of a project: workspace ⊕ overrides (by token name). */
export function applyOverrides(workspace: TokenSet, overrides: TokenOverrides | null | undefined): TokenSet {
  if (!overrides) return workspace
  return mergeTokenSets(workspace, overrides, 'merge')
}

/** The overrides that turn `workspace` into `effective`: changed or new tokens only. */
export function computeOverrides(workspace: TokenSet, effective: TokenSet): TokenOverrides {
  const out: Record<string, unknown[]> = {}
  for (const c of CATEGORIES) {
    const base = new Map((workspace[c] as Array<{ name: string }>).map((t) => [t.name, JSON.stringify(t)]))
    const diff = (effective[c] as Array<{ name: string }>).filter((t) => base.get(t.name) !== JSON.stringify(t))
    if (diff.length) out[c] = diff
  }
  return out as TokenOverrides
}

/** Tokens the workspace has that the effective set dropped — overrides can't express removal. */
export function droppedTokens(workspace: TokenSet, effective: TokenSet): string[] {
  const out: string[] = []
  for (const c of CATEGORIES) {
    const keep = new Set((effective[c] as Array<{ name: string }>).map((t) => t.name))
    for (const t of workspace[c] as Array<{ name: string }>) if (!keep.has(t.name)) out.push(t.name)
  }
  return out
}

export function overrideCount(o: TokenOverrides | null | undefined): number {
  if (!o) return 0
  return CATEGORIES.reduce((n, c: TokenCategory) => n + ((o[c] as unknown[] | undefined)?.length ?? 0), 0)
}

export interface PublishFile {
  path: string
  content: string
}

export interface PublishMeta {
  /** Version label tagged on publish. */
  version: string
  /** "workspace" or the project slug. */
  scope: string
  /** Where the tokens are edited (a console deep link), for the file headers. */
  source?: string
}

/** Normalise a folder path: no leading/trailing slashes, no `..`. */
export function cleanDir(dir: string): string {
  return dir
    .split('/')
    .map((s) => s.trim())
    .filter((s) => s && s !== '.' && s !== '..')
    .join('/')
}

export const PUBLISH_FILES = [
  { name: 'tokens.json', label: 'W3C Design Tokens JSON' },
  { name: 'tokens.css', label: 'CSS custom properties (light + .dark)' },
  { name: 'theme.css', label: 'Tailwind v4 @theme' },
  { name: 'tailwind.preset.js', label: 'Tailwind v3 preset' },
] as const

/** The files a publish writes, under `dir`. */
export function publishFiles(tokens: TokenSet, dir: string, meta: PublishMeta): PublishFile[] {
  const base = cleanDir(dir)
  const at = (name: string) => (base ? `${base}/${name}` : name)
  const header = (style: 'css' | 'js') => {
    const lines = [
      'Generated by Adhar Design — Design Tokens.',
      `Scope: ${meta.scope} · Version: ${meta.version}`,
      ...(meta.source ? [`Edit the tokens at ${meta.source}, then publish again; hand edits here are overwritten.`] : []),
    ]
    return style === 'css' ? `/*\n${lines.map((l) => ` * ${l}`).join('\n')}\n */\n` : `/**\n${lines.map((l) => ` * ${l}`).join('\n')}\n */\n`
  }
  const w3c = { ...tokensToW3C(tokens), $description: `Adhar Design tokens — ${meta.scope}, ${meta.version}` }
  return [
    { path: at('tokens.json'), content: `${JSON.stringify(w3c, null, 2)}\n` },
    { path: at('tokens.css'), content: `${header('css')}${tokensToCss(tokens)}\n` },
    { path: at('theme.css'), content: `${header('css')}${tokensToTailwindV4(tokens)}\n` },
    { path: at('tailwind.preset.js'), content: `${header('js')}${tokensToTailwindV3(tokens)}` },
  ]
}

/** Branch name for a token publish: `design/tokens-<scope>-<yyyymmdd-hhmm>`. */
export function publishBranch(scope: string, now = new Date()): string {
  const p = (n: number) => String(n).padStart(2, '0')
  const stamp = `${now.getUTCFullYear()}${p(now.getUTCMonth() + 1)}${p(now.getUTCDate())}-${p(now.getUTCHours())}${p(now.getUTCMinutes())}`
  const s = scope.toLowerCase().replace(/[^a-z0-9-]+/g, '-').replace(/^-+|-+$/g, '') || 'workspace'
  return `design/tokens-${s}-${stamp}`
}

/** Markdown body for the pull request. */
export function publishPrBody(files: PublishFile[], meta: PublishMeta, summary: { count: number; overrides?: number }): string {
  return [
    `Design tokens from **Adhar Design** — scope \`${meta.scope}\`, version **${meta.version}**.`,
    '',
    `${summary.count} tokens${summary.overrides ? ` (${summary.overrides} project overrides on top of the workspace set)` : ''}.`,
    '',
    '| File | |',
    '|---|---|',
    ...files.map((f) => `| \`${f.path}\` | ${PUBLISH_FILES.find((x) => f.path.endsWith(x.name))?.label ?? ''} |`),
    '',
    meta.source ? `Edit the tokens: ${meta.source}` : '',
  ].join('\n').trim()
}
