/**
 * The TestRun a runner creates. `__RUN_NAME__` and `__TRIGGER__` are filled
 * in by the script; everything else comes from the committed config.
 */
export function testRunTemplate(input: { test: string; config: PerfTestConfig; commit?: string }) {
  const { test, config } = input
  const commit = (input.commit ?? '').slice(0, 40)
  const env = Object.entries(config.env)
  return {
    apiVersion: 'k6.io/v1alpha1',
    kind: 'TestRun',
    metadata: {
      name: RUN_NAME_TOKEN,
      namespace: config.namespace || 'default',
      labels: {
        [LABEL_MANAGED]: 'adhar-console',
        [LABEL_TEST]: test,
        [LABEL_TRIGGER]: TRIGGER_TOKEN,
        // The runner owns this run's harvest — the console must not race it.
        [LABEL_RUNNER]: 'job',
        ...(commit ? { [LABEL_COMMIT]: commit } : {}),
        ...(targetApplication(config) ? { [LABEL_APPLICATION]: targetApplication(config)! } : {}),
      },
    },
    spec: withPinnedImages({
      parallelism: config.parallelism,
      script: { configMap: { name: artefactName(test), file: SCRIPT_FILE } },
      // The CRD defaults `paused` to the STRING "true".
      paused: 'false',
      ...(config.arguments ? { arguments: config.arguments } : {}),
      ...(env.length ? { runner: { env: env.map(([name, value]) => ({ name, value })) } } : {}),
    }),
  }
}

/** The whole artefact ConfigMap for one test. */
export function artefactConfigMap(input: { test: string; config: PerfTestConfig; script: string; commit?: string }) {
  const { test, config } = input
  const ns = config.namespace || 'default'
  const commit = (input.commit ?? '').slice(0, 40)
  return {
    apiVersion: 'v1',
    kind: 'ConfigMap',
    metadata: {
      name: artefactName(test),
      namespace: ns,
      labels: {
        [LABEL_MANAGED]: 'adhar-console',
        [LABEL_TEST]: test,
        ...(commit ? { [LABEL_COMMIT]: commit } : {}),
      },
    },
    data: {
      [SCRIPT_FILE]: input.script,
      [TESTRUN_KEY]: `${JSON.stringify(testRunTemplate({ test, config, commit }), null, 2)}\n`,
      [GATE_KEY]: gateEnv({
        test,
        namespace: ns,
        commit,
        gate: config.gate,
        baseline: config.baseline,
        application: targetApplication(config),
      }),
      [RUNNER_KEY]: RUN_SCRIPT,
    },
  }
}

/* ─────────────────────────── RBAC ─────────────────────────── */

/**
 * What the runner may do in the test's namespace — exactly what run.sh
 * calls, nothing cluster-wide.
 */
export function runnerRbac(namespace: string) {
  const labels = { [LABEL_MANAGED]: 'adhar-console' }
  return [
    { apiVersion: 'v1', kind: 'ServiceAccount', metadata: { name: RUNNER_SA, namespace, labels } },
    {
      apiVersion: 'rbac.authorization.k8s.io/v1',
      kind: 'Role',
      metadata: { name: RUNNER_SA, namespace, labels },
      rules: [
        { apiGroups: ['k6.io'], resources: ['testruns'], verbs: ['get', 'list', 'watch', 'create', 'patch', 'delete'] },
        { apiGroups: [''], resources: ['pods'], verbs: ['get', 'list'] },
        { apiGroups: [''], resources: ['pods/log'], verbs: ['get'] },
        { apiGroups: [''], resources: ['configmaps'], verbs: ['get', 'list', 'create', 'patch', 'update', 'delete'] },
      ],
    },
    {
      apiVersion: 'rbac.authorization.k8s.io/v1',
      kind: 'RoleBinding',
      metadata: { name: RUNNER_SA, namespace, labels },
      roleRef: { apiGroup: 'rbac.authorization.k8s.io', kind: 'Role', name: RUNNER_SA },
      subjects: [{ kind: 'ServiceAccount', name: RUNNER_SA, namespace }],
    },
  ]
}

