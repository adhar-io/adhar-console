/**
 * Unattended runs: schedules, CI gates and promotion verification.
 *
 * ---------------------------------------------------------------------------
 * ONE RUNNER, THREE CALLERS
 * ---------------------------------------------------------------------------
 * A nightly CronJob, a Tekton step after deploy and a Kargo verification all
 * need the same thing: start the committed test, wait for it, keep its
 * result, judge it against the gate and exit non-zero when it fails. That
 * logic is ONE POSIX shell script (`run.sh`, below) that needs nothing but
 * `kubectl` and `awk`, so it runs in any kubectl image.
 *
 * The script is not copied into each caller. It is materialised into the
 * test's script ConfigMap (`k6-<test>`) beside everything else a run needs:
 *
 *   script.js     the k6 script, as committed
 *   testrun.json  the TestRun to create, with the run name left as a token
 *   gate.env      the gate and baseline from test.json, as shell variables
 *   run.sh        this runner
 *
 * The console rewrites that ConfigMap whenever the test is run, its gate is
 * committed or a schedule is saved, stamped with the commit it came from.
 * Callers only ever say "run test X in namespace Y" — so changing a budget
 * in git changes what every schedule and pipeline enforces, with no YAML to
 * chase.
 *
 * Pure: manifest and text generation only.
 */

export const RUNNER_SA = 'adhar-perf-runner'
export const DEFAULT_RUNNER_IMAGE = 'alpine/k8s:1.31.1'
export const RUNNER_KEY = 'run.sh'
export const GATE_KEY = 'gate.env'
export const TESTRUN_KEY = 'testrun.json'

export const RUN_NAME_TOKEN = '__RUN_NAME__'
export const TRIGGER_TOKEN = '__TRIGGER__'

/** `checkout-load` → `k6-checkout-load`, the generated ConfigMap. */
export const artefactName = (test: string) => `k6-${test}`.slice(0, 253)

/* ─────────────────────────── the runner script ─────────────────────────── */

/*
 * Written with String.raw so awk's regex backslashes survive, and with `%{`
 * standing in for the shell's `${` — a template literal would otherwise try
 * to interpolate every shell parameter expansion.
 */
export const RUN_SCRIPT = String.raw`#!/bin/sh
# Adhar performance runner — generated by the Adhar console. Do not edit:
# it is rewritten from the console whenever the test is run or its gate saved.
#
# Starts one committed k6 test through the k6 operator, waits for it,
# harvests every runner's end-of-test summary into a result ConfigMap
# (k6-result-<run>), evaluates the performance gate from gate.env and exits
# non-zero when the gate fails — so a CronJob, a Tekton step or a Kargo
# verification can act on the verdict.
#
#   TEST          test name (required)
#   NS            namespace of the test (defaults to the pod's own)
#   TRIGGER       schedule | ci | manual            (default manual)
#   SCHEDULE      name of the schedule, recorded on the result
#   ENFORCE_GATE  true: exit 1 when the gate fails  (default true)
#   CLEANUP       true: delete the TestRun after harvesting (default true)
#   RETAIN        results kept per test             (default 50)
#   TIMEOUT       seconds to wait for the run       (default 7200)
#   VERDICT_FILE  optional path the verdict (pass|fail) is written to
set -u

TEST="%{TEST:?TEST is required}"
NS="%{NS:-}"
if [ -z "$NS" ] && [ -r /var/run/secrets/kubernetes.io/serviceaccount/namespace ]; then
  NS="$(cat /var/run/secrets/kubernetes.io/serviceaccount/namespace)"
fi
NS="%{NS:-default}"
TRIGGER="%{TRIGGER:-manual}"
SCHEDULE="%{SCHEDULE:-}"
ENFORCE_GATE="%{ENFORCE_GATE:-true}"
CLEANUP="%{CLEANUP:-true}"
RETAIN="%{RETAIN:-50}"
TIMEOUT="%{TIMEOUT:-7200}"
POLL="%{POLL:-10}"
KUBECTL="%{KUBECTL:-kubectl}"
CM="k6-$TEST"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

log() { printf '[perf] %s\n' "$*"; }
k() { "$KUBECTL" -n "$NS" "$@"; }
gt() { awk -v a="$1" -v b="$2" 'BEGIN { exit !(a + 0 > b + 0) }'; }
lt() { awk -v a="$1" -v b="$2" 'BEGIN { exit !(a + 0 < b + 0) }'; }
calc() { awk -v a="$1" -v b="$2" "BEGIN { print $3 }"; }

# ── 1. the artefact ────────────────────────────────────────────────────────
if ! k get configmap "$CM" -o jsonpath='{.data.gate\.env}' > "$WORK/gate.env"; then
  log "ConfigMap $NS/$CM not found. Run the test once from the console (or save its gate) to materialise it."
  exit 2
fi
PERF_COMMIT='' TARGET_APP='' GATE_P95_MS='' GATE_P99_MS='' GATE_AVG_MS='' GATE_ERROR_PCT='' GATE_MIN_RPS=''
GATE_REQUIRE_THRESHOLDS=true GATE_FAIL_ON_REGRESSION=false
TOL_LATENCY_PCT=10 TOL_ERROR_PTS=0.5 TOL_RPS_PCT=10
BASE_RUN='' BASE_P95_MS='' BASE_P99_MS='' BASE_AVG_MS='' BASE_ERROR_PCT='' BASE_RPS=''
. "$WORK/gate.env"
k get configmap "$CM" -o jsonpath='{.data.testrun\.json}' > "$WORK/testrun.json"
if [ ! -s "$WORK/testrun.json" ]; then log "$CM has no testrun.json"; exit 2; fi

# ── 2. start the run ───────────────────────────────────────────────────────
RUN="$(printf '%s' "$TEST" | cut -c1-40)-$(date -u +%Y%m%d-%H%M%S)"
sed -e "s/__RUN_NAME__/$RUN/g" -e "s/__TRIGGER__/$TRIGGER/g" "$WORK/testrun.json" > "$WORK/run.json"
STARTED="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
if ! k create -f "$WORK/run.json" > /dev/null; then log "could not create TestRun $RUN"; exit 2; fi
if [ -n "$SCHEDULE" ]; then k label testrun "$RUN" "adhar.io/perf-schedule=$SCHEDULE" > /dev/null 2>&1 || true; fi
log "started TestRun $NS/$RUN (trigger: $TRIGGER, commit: %{PERF_COMMIT:-unknown})"

# ── 3. wait for it ─────────────────────────────────────────────────────────
waited=0
STAGE=''
while :; do
  STAGE="$(k get testrun "$RUN" -o jsonpath='{.status.stage}' 2> /dev/null || true)"
  case "$STAGE" in finished|error|stopped) break ;; esac
  if [ "$waited" -ge "$TIMEOUT" ]; then STAGE=timeout; log "gave up waiting after %{TIMEOUT}s"; break; fi
  sleep "$POLL"
  waited=$((waited + POLL))
done
FINISHED="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
PAR="$(k get testrun "$RUN" -o jsonpath='{.spec.parallelism}' 2> /dev/null || true)"
log "TestRun ended in stage $STAGE"

# ── 4. harvest every runner's summary ──────────────────────────────────────
PODS="$(k get pods -l "k6_cr=$RUN" -o name 2> /dev/null | grep -v -e '-initializer-' -e '-starter-' || true)"
if [ -z "$PODS" ]; then PODS="$(k get pods -o name 2> /dev/null | grep "^pod/$RUN-[0-9]" || true)"; fi
: > "$WORK/summary.txt"
EXIT=0
for p in $PODS; do
  printf '=== adhar-perf runner %s ===\n' "%{p#pod/}" >> "$WORK/summary.txt"
  k logs "$p" 2> /dev/null \
    | awk '/running \(|\[ *[0-9]+%|\[=/ { buf = ""; next } { buf = buf $0 "\n" } END { printf "%s", buf }' \
    | tail -n 400 >> "$WORK/summary.txt"
  code="$(k get "$p" -o jsonpath='{.status.containerStatuses[0].state.terminated.exitCode}' 2> /dev/null || true)"
  if [ "$code" = 99 ]; then EXIT=99; elif [ -n "$code" ] && [ "$code" != 0 ] && [ "$EXIT" = 0 ]; then EXIT="$code"; fi
done
cat "$WORK/summary.txt"

# ── 5. headline numbers (worst percentile, summed throughput) ──────────────
awk '
function ms(s,   t, tok, n, u) {
  t = 0
  while (match(s, /^[0-9.]+(ms|µs|μs|us|ns|h|m|s)/)) {
    tok = substr(s, 1, RLENGTH); s = substr(s, RLENGTH + 1)
    match(tok, /^[0-9.]+/); n = substr(tok, 1, RLENGTH) + 0; u = substr(tok, RLENGTH + 1)
    if (u == "h") t += n * 3600000; else if (u == "m") t += n * 60000; else if (u == "s") t += n * 1000
    else if (u == "ms") t += n; else if (u == "ns") t += n / 1000000; else t += n / 1000
  }
  return t
}
function flush(   w) {
  if (!seen) return
  if (p95 != "" && (P95 == "" || p95 + 0 > P95 + 0)) P95 = p95
  if (p99 != "" && (P99 == "" || p99 + 0 > P99 + 0)) P99 = p99
  w = (reqs == "" ? 0 : reqs + 0)
  if (avg != "") { AN += avg * w; AW += w; AS += avg; AC++ }
  if (err != "") { EN += err * w; EW += w; ES += err; EC++ }
  if (rps != "") { RPS += rps; HAVE_RPS = 1 }
  seen = 0; p95 = ""; p99 = ""; avg = ""; err = ""; rps = ""; reqs = ""
}
index($0, "=== adhar-perf runner") == 1 { flush(); next }
{
  line = $0
  sub(/^[ \t]+/, "", line)
  sub(/^(✓|✗)[ \t]+/, "", line)
  if (!match(line, /^[a-z0-9_]+\.\.+:/)) next
  name = substr(line, 1, RLENGTH); sub(/\.+:$/, "", name)
  nf = split(substr(line, RLENGTH + 1), f, /[ \t]+/)
  if (name == "http_req_duration") {
    seen = 1
    for (i = 1; i <= nf; i++) {
      if (f[i] ~ /^p\(95\)=/) p95 = ms(substr(f[i], 7))
      else if (f[i] ~ /^p\(99\)=/) p99 = ms(substr(f[i], 7))
      else if (f[i] ~ /^avg=/) avg = ms(substr(f[i], 5))
    }
  } else if (name == "http_req_failed") {
    seen = 1
    for (i = 1; i <= nf; i++) if (f[i] ~ /^[0-9.]+%$/) { err = substr(f[i], 1, length(f[i]) - 1); break }
  } else if (name == "http_reqs") {
    seen = 1
    for (i = 1; i <= nf; i++) {
      if (f[i] ~ /^[0-9.]+\/s$/) rps = substr(f[i], 1, length(f[i]) - 2)
      else if (reqs == "" && f[i] ~ /^[0-9.]+$/) reqs = f[i]
    }
  }
}
END {
  flush()
  print "M_P95=\047" P95 "\047"
  print "M_P99=\047" P99 "\047"
  if (AW > 0) print "M_AVG=\047" AN / AW "\047"; else if (AC) print "M_AVG=\047" AS / AC "\047"; else print "M_AVG=\047\047"
  if (EW > 0) print "M_ERR=\047" EN / EW "\047"; else if (EC) print "M_ERR=\047" ES / EC "\047"; else print "M_ERR=\047\047"
  if (HAVE_RPS) print "M_RPS=\047" RPS "\047"; else print "M_RPS=\047\047"
}' "$WORK/summary.txt" > "$WORK/metrics.env"
. "$WORK/metrics.env"
log "p95=%{M_P95:-?}ms p99=%{M_P99:-?}ms avg=%{M_AVG:-?}ms errors=%{M_ERR:-?}% rps=%{M_RPS:-?}"

# ── 6. the gate ────────────────────────────────────────────────────────────
FAIL=''
REGRESSED=''
reason() { FAIL="%{FAIL:+$FAIL; }$*"; }
regress() { REGRESSED="%{REGRESSED:+$REGRESSED; }$*"; }
if [ "$STAGE" != finished ]; then reason "run ended in stage $STAGE"; fi
if [ -z "$M_P95$M_AVG$M_ERR$M_RPS" ]; then reason "no end-of-test summary was found"; fi
if [ "$GATE_REQUIRE_THRESHOLDS" = true ] && [ "$EXIT" = 99 ]; then reason "script thresholds crossed"; fi
ceiling() {
  [ -n "$3" ] || return 0
  if [ -z "$2" ]; then reason "$1 not reported"; elif gt "$2" "$3"; then reason "$1 $2 > $3"; fi
}
ceiling p95_ms "$M_P95" "$GATE_P95_MS"
ceiling p99_ms "$M_P99" "$GATE_P99_MS"
ceiling avg_ms "$M_AVG" "$GATE_AVG_MS"
ceiling error_pct "$M_ERR" "$GATE_ERROR_PCT"
if [ -n "$GATE_MIN_RPS" ]; then
  if [ -z "$M_RPS" ]; then reason "rps not reported"; elif lt "$M_RPS" "$GATE_MIN_RPS"; then reason "rps $M_RPS < $GATE_MIN_RPS"; fi
fi
if [ -n "$BASE_RUN" ]; then
  latency() {
    [ -n "$2" ] && [ -n "$3" ] || return 0
    lim="$(calc "$3" "$TOL_LATENCY_PCT" 'a * (1 + b / 100)')"
    if gt "$2" "$lim"; then regress "$1 $2 > $lim (baseline $3)"; fi
  }
  latency p95_ms "$M_P95" "$BASE_P95_MS"
  latency p99_ms "$M_P99" "$BASE_P99_MS"
  latency avg_ms "$M_AVG" "$BASE_AVG_MS"
  if [ -n "$M_ERR" ] && [ -n "$BASE_ERROR_PCT" ]; then
    lim="$(calc "$BASE_ERROR_PCT" "$TOL_ERROR_PTS" 'a + b')"
    if gt "$M_ERR" "$lim"; then regress "error_pct $M_ERR > $lim (baseline $BASE_ERROR_PCT)"; fi
  fi
  if [ -n "$M_RPS" ] && [ -n "$BASE_RPS" ]; then
    lim="$(calc "$BASE_RPS" "$TOL_RPS_PCT" 'a * (1 - b / 100)')"
    if lt "$M_RPS" "$lim"; then regress "rps $M_RPS < $lim (baseline $BASE_RPS)"; fi
  fi
  if [ -n "$REGRESSED" ]; then
    log "regressed against $BASE_RUN: $REGRESSED"
    if [ "$GATE_FAIL_ON_REGRESSION" = true ]; then reason "regression vs $BASE_RUN: $REGRESSED"; fi
  fi
fi
VERDICT=pass
if [ -n "$FAIL" ]; then VERDICT=fail; fi
NOTE="$FAIL"
if [ -z "$NOTE" ] && [ -n "$REGRESSED" ]; then NOTE="regressed (not gating): $REGRESSED"; fi

# ── 7. record the result ───────────────────────────────────────────────────
RESULT="k6-result-$RUN"
if k create configmap "$RESULT" --from-file="summary.txt=$WORK/summary.txt" > /dev/null; then
  k label configmap "$RESULT" adhar.io/perf-result=true "adhar.io/perf-test=$TEST" \
    "adhar.io/perf-trigger=$TRIGGER" app.kubernetes.io/managed-by=adhar-console \
    %{PERF_COMMIT:+"adhar.io/perf-commit=$PERF_COMMIT"} %{SCHEDULE:+"adhar.io/perf-schedule=$SCHEDULE"} \
    %{TARGET_APP:+"adhar.io/application=$TARGET_APP"} > /dev/null
  k annotate configmap "$RESULT" "adhar.io/perf-run=$RUN" "adhar.io/perf-started=$STARTED" \
    "adhar.io/perf-finished=$FINISHED" "adhar.io/perf-stage=$STAGE" "adhar.io/perf-exit-code=$EXIT" \
    "adhar.io/perf-verdict=$VERDICT" "adhar.io/perf-verdict-reasons=$NOTE" "adhar.io/perf-parallelism=%{PAR:-1}" > /dev/null
  log "recorded $NS/$RESULT"
else
  log "could not record the result ConfigMap"
fi
k annotate testrun "$RUN" "adhar.io/perf-harvested=$RESULT" --overwrite > /dev/null 2>&1 || true
if [ "$CLEANUP" = true ]; then k delete testrun "$RUN" --wait=false > /dev/null 2>&1 || true; fi

# Retention: keep the newest $RETAIN results for this test.
k get configmap -l "adhar.io/perf-result=true,adhar.io/perf-test=$TEST" \
  --sort-by=.metadata.creationTimestamp -o name 2> /dev/null \
  | awk -v n="$RETAIN" '{ a[NR] = $0 } END { for (i = 1; i <= NR - n; i++) print a[i] }' \
  | while read -r old; do k delete "$old" > /dev/null 2>&1 || true; done

if [ -n "%{VERDICT_FILE:-}" ]; then printf '%s' "$VERDICT" > "$VERDICT_FILE"; fi
log "verdict: $VERDICT%{NOTE:+ — $NOTE}"
if [ "$VERDICT" = fail ] && [ "$ENFORCE_GATE" = true ]; then exit 1; fi
exit 0
`.replaceAll('%{', '${')

