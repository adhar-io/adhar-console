export interface ScheduleInput {
  name: string
  namespace: string
  test: string
  cron: string
  timeZone?: string
  suspend: boolean
  /** Fail the Job when the gate fails, so CronJob history shows it. */
  enforceGate: boolean
  description?: string
  image: string
  /** Results kept for the test. */
  retain: number
  timeoutSecs: number
}

export interface PerfSchedule extends ScheduleInput {
  uid?: string
  createdAt?: string
  lastScheduleTime?: string
  lastSuccessfulTime?: string
  /** Jobs currently running for this schedule. */
  active: number
}

export const ANN_DESCRIPTION = 'adhar.io/perf-description'

/** CronJob names are capped at 52 so the controller's Job suffix fits. */
export const SCHEDULE_NAME_RE = /^[a-z0-9]([a-z0-9-]{0,50}[a-z0-9])?$/

export function scheduleNameError(name: string): string | null {
  if (!name) return 'A name is required.'
  if (!SCHEDULE_NAME_RE.test(name)) return 'Lowercase letters, numbers and dashes, at most 52 characters.'
  return null
}

export function defaultScheduleName(test: string, suffix = 'scheduled'): string {
  return `${test.slice(0, 52 - suffix.length - 1)}-${suffix}`.replace(/-+$/, '')
}

function runnerEnv(input: { test: string; namespace: string; trigger: string; schedule?: string; enforceGate: boolean; retain: number; timeoutSecs: number }) {
  return [
    { name: 'TEST', value: input.test },
    { name: 'NS', value: input.namespace },
    { name: 'TRIGGER', value: input.trigger },
    ...(input.schedule ? [{ name: 'SCHEDULE', value: input.schedule }] : []),
    { name: 'ENFORCE_GATE', value: input.enforceGate ? 'true' : 'false' },
    { name: 'CLEANUP', value: 'true' },
    { name: 'RETAIN', value: String(input.retain) },
    { name: 'TIMEOUT', value: String(input.timeoutSecs) },
  ]
}

export function cronJobManifest(s: ScheduleInput) {
  const labels = {
    [LABEL_MANAGED]: 'adhar-console',
    [LABEL_TEST]: s.test,
    [LABEL_SCHEDULE]: s.name,
  }
  return {
    apiVersion: 'batch/v1',
    kind: 'CronJob',
    metadata: {
      name: s.name,
      namespace: s.namespace,
      labels,
      annotations: { [ANN_DESCRIPTION]: s.description ?? '' },
    },
    spec: {
      schedule: s.cron.trim(),
      ...(s.timeZone ? { timeZone: s.timeZone } : {}),
      suspend: s.suspend,
      // Two load tests against the same system at once measure each other.
      concurrencyPolicy: 'Forbid',
      startingDeadlineSeconds: 600,
      successfulJobsHistoryLimit: 3,
      failedJobsHistoryLimit: 5,
      jobTemplate: {
        metadata: { labels },
        spec: {
          backoffLimit: 0,
          activeDeadlineSeconds: s.timeoutSecs + 900,
          ttlSecondsAfterFinished: 7 * 24 * 3600,
          template: {
            metadata: { labels },
            spec: {
              serviceAccountName: RUNNER_SA,
              restartPolicy: 'Never',
              containers: [{
                name: 'perf-runner',
                image: s.image || DEFAULT_RUNNER_IMAGE,
                command: ['sh', `/perf/${RUNNER_KEY}`],
                env: runnerEnv({
                  test: s.test,
                  namespace: s.namespace,
                  trigger: 'schedule',
                  schedule: s.name,
                  enforceGate: s.enforceGate,
                  retain: s.retain,
                  timeoutSecs: s.timeoutSecs,
                }),
                resources: { requests: { cpu: '10m', memory: '32Mi' }, limits: { memory: '128Mi' } },
                volumeMounts: [{ name: 'perf', mountPath: '/perf', readOnly: true }],
              }],
              volumes: [{
                name: 'perf',
                configMap: { name: artefactName(s.test), items: [{ key: RUNNER_KEY, path: RUNNER_KEY }] },
              }],
            },
          },
        },
      },
    },
  }
}

interface CronJobLike {
  metadata: {
    name: string
    namespace?: string
    uid?: string
    creationTimestamp?: string
    labels?: Record<string, string>
    annotations?: Record<string, string>
  }
  spec?: {
    schedule?: string
    timeZone?: string
    suspend?: boolean
    jobTemplate?: {
      spec?: {
        template?: {
          spec?: {
            containers?: Array<{ image?: string; env?: Array<{ name: string; value?: string }> }>
          }
        }
      }
    }
  }
  status?: { lastScheduleTime?: string; lastSuccessfulTime?: string; active?: unknown[] }
}

/** Read a schedule back from its CronJob; null for CronJobs that are not ours. */
export function scheduleFromCronJob(cj: CronJobLike): PerfSchedule | null {
  const labels = cj.metadata.labels ?? {}
  const test = labels[LABEL_TEST]
  if (!test || !labels[LABEL_SCHEDULE]) return null
  const container = cj.spec?.jobTemplate?.spec?.template?.spec?.containers?.[0]
  const env = new Map((container?.env ?? []).map((e) => [e.name, e.value ?? '']))
  const retain = Number(env.get('RETAIN'))
  const timeout = Number(env.get('TIMEOUT'))
  return {
    name: cj.metadata.name,
    namespace: cj.metadata.namespace ?? 'default',
    uid: cj.metadata.uid,
    createdAt: cj.metadata.creationTimestamp,
    test,
    cron: cj.spec?.schedule ?? '',
    timeZone: cj.spec?.timeZone || undefined,
    suspend: Boolean(cj.spec?.suspend),
    enforceGate: env.get('ENFORCE_GATE') !== 'false',
    description: cj.metadata.annotations?.[ANN_DESCRIPTION] || undefined,
    image: container?.image ?? DEFAULT_RUNNER_IMAGE,
    retain: Number.isFinite(retain) && retain > 0 ? retain : 50,
    timeoutSecs: Number.isFinite(timeout) && timeout > 0 ? timeout : 7200,
    lastScheduleTime: cj.status?.lastScheduleTime,
    lastSuccessfulTime: cj.status?.lastSuccessfulTime,
    active: cj.status?.active?.length ?? 0,
  }
}

/**
 * "Run now": a Job stamped from the CronJob's template, exactly as
 * `kubectl create job --from=cronjob/…` does, owned by the CronJob so it is
 * cleaned up with it.
 */
export function manualJobFromSchedule(
  s: PerfSchedule,
  stamp: string,
) {
  const base = cronJobManifest(s)
  const name = `${s.name.slice(0, 63 - stamp.length - 3)}-m-${stamp}`
  const tmpl = base.spec.jobTemplate
  const container = tmpl.spec.template.spec.containers[0]
  return {
    apiVersion: 'batch/v1',
    kind: 'Job',
    metadata: {
      name,
      namespace: s.namespace,
      labels: tmpl.metadata.labels,
      annotations: { 'cronjob.kubernetes.io/instantiate': 'manual' },
      ...(s.uid
        ? {
          ownerReferences: [{
            apiVersion: 'batch/v1',
            kind: 'CronJob',
            name: s.name,
            uid: s.uid,
            controller: false,
            blockOwnerDeletion: false,
          }],
        }
        : {}),
    },
    spec: {
      ...tmpl.spec,
      template: {
        ...tmpl.spec.template,
        spec: {
          ...tmpl.spec.template.spec,
          containers: [{
            ...container,
            env: container.env.map((e) => e.name === 'TRIGGER' ? { ...e, value: 'manual' } : e),
          }],
        },
      },
    },
  }
}

