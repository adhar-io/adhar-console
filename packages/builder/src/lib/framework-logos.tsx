// Paths are the official Simple Icons (https://simpleicons.org) marks — CC0 licence.
// Each logo is a single solid-fill path so it renders identically regardless of
// how many times it appears on the page (no gradient/clipPath ID collisions).

interface LogoProps {
  size?: number;
  monochrome?: boolean;
  className?: string;
  title?: string;
}

interface LogoConfig {
  name: string;
  color: string;
  path: string;
}

function makeLogo({ name, color, path }: LogoConfig) {
  return function Logo({ size = 18, monochrome = false, className, title }: LogoProps) {
    const c = monochrome ? 'currentColor' : color;
    return (
      <svg
        width={size}
        height={size}
        viewBox='0 0 24 24'
        xmlns='http://www.w3.org/2000/svg'
        className={className}
        role='img'
        aria-label={title || name}
        style={{ display: 'inline-block', flexShrink: 0 }}
      >
        <title>{title || name}</title>
        <path d={path} fill={c} />
      </svg>
    );
  };
}

